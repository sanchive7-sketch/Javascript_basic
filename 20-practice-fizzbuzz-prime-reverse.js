function isPrime(n) {
  if (n < 2) return false;
  for (let i = 2; i * i <= n; i++) {
    if (n % i === 0) return false;
  }
  return true;
}
console.log(isPrime(7));
console.log(isPrime(10));
function reverseStr(s) {
  return s.split("").reverse().join("");
}
console.log(reverseStr("hello"));
